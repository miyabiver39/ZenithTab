/** The region's catalog, in display order (defaults first, then the rest). Fresh copies. */
export function getSiteCatalog(lang: PresetLanguage): CatalogSite[] {
  return SITES[lang].map((site) => ({ ...site }));
}

/** Distinct category labels of a region's catalog, in first-seen order. */
export function getSiteCategories(lang: PresetLanguage): string[] {
  return Array.from(new Set(SITES[lang].map((s) => s.category)));
}

