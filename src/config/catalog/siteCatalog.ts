import type { PresetLanguage } from '../defaults/regionalPresets';

/**
 * Curated, per-region lists of everyday sites — the pool the "add from
 * catalog" picker offers for Shortcuts and the Dock, and the source the
 * first-run Dock / Shortcut defaults are derived from (`regionalPresets`).
 *
 * Aimed at the general public of each region, not developers: portals,
 * mail, maps, video, social, shopping, news, travel, banks, AI. Titles and
 * categories are already in the region's language because they are stored
 * verbatim in the user's data (the Shortcuts widget uses free-text
 * categories).
 *
 * `dock` / `shortcut` are 1-based ranks in the first-run defaults; entries
 * without them are catalog-only.
 */
export interface CatalogSite {
  /** Stable id, also the suffix of the default `dock-<id>` / `app-<id>` item ids. */
  id: string;
  title: string;
  url: string;
  /** Localized category label (chip in the picker, category in the widget). */
  category: string;
  /** DOCK_ICON_LIBRARY key used when the site lands in the Dock. */
  icon: string;
  /** Position in the first-run Dock (1 = leftmost). */
  dock?: number;
  /** Position in the first-run Shortcuts widget. */
  shortcut?: number;
  /** Dock label when it should differ from `title` (e.g. Latin script in the Dock). */
  dockLabel?: string;
}

type Row = [id: string, title: string, url: string, category: string, icon: string, dock?: number, shortcut?: number, dockLabel?: string];

const rows = (list: Row[]): CatalogSite[] =>
  list.map(([id, title, url, category, icon, dock, shortcut, dockLabel]) => ({
    id,
    title,
    url,
    category,
    icon,
    ...(dock ? { dock } : {}),
    ...(shortcut ? { shortcut } : {}),
    ...(dockLabel ? { dockLabel } : {}),
  }));

